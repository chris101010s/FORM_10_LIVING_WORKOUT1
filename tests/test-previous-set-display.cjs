const assert=require('node:assert/strict');
const {execFileSync}=require('node:child_process');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'form-previous-display-'));
try{
 const src=path.resolve('src');
 execFileSync(path.resolve('node_modules/.bin/tsc'),['--target','ES2022','--module','commonjs','--strict','--skipLibCheck','--rootDir',src,'--outDir',tmp,path.join(src,'utils/previousSetDisplay.ts')],{cwd:tmp,stdio:'inherit'});
 const {previousActualsForRows}=require(path.join(tmp,'utils/previousSetDisplay.js'));
 const row=(id,index,kind='work',extra=false)=>({id,exerciseId:'bench',plannedIndex:index,targetId:'t'+index,planPositionId:'new-day',kind,isExtraSet:extra});
 const set=(id,index,kg,extra={})=>({id,exerciseId:'bench',plannedIndex:index,weightKg:kg,reps:10,rir:0,at:'2026-11-20T10:00:00Z',...extra});
 const workout=(id,day,sets)=>({id,finishedAt:'2026-11-'+day+'T12:00:00Z',startedAt:'2026-11-'+day+'T11:00:00Z',name:id,sets});
 const first=row('r1',0),second=row('r2',1),third=row('r3',2);
 const older=workout('older','17',[set('old0',0,40),set('old1',1,42),set('old2',2,45)]);
 const latest=workout('latest','22',[set('now0',0,50),set('now2',2,55)]);
 const result=previousActualsForRows([older,latest],[first,second,third],{workout:older,byTargetId:{t0:older.sets[0]}});
 assert.equal(result.r1.set.weightKg,50,'newest session wins over an older exact plan match');
 assert.equal(result.r1.set.rir,0,'RIR zero is kept');
 assert.equal(result.r1.source,'exercise','changed plan is explicitly exercise-only');
 assert.equal(result.r2,undefined,'skipped second set is not shifted');
 assert.equal(result.r3.set.weightKg,55,'third set keeps its index');
 const match=previousActualsForRows([latest],[first],{workout:latest,byTargetId:{t0:latest.sets[0]}});
 assert.equal(match.r1.source,'comparable','unchanged plan receives exact match');
 const legacy=workout('legacy','24',[set('leg0',undefined,61),set('leg1',undefined,62)]);
 const oldValues=previousActualsForRows([legacy],[first,second,third]);
 assert.equal(oldValues.r2.set.weightKg,62,'legacy data without indices uses set order');
 assert.equal(oldValues.r3,undefined);
 const onlyWarmup=workout('warmup','25',[set('warm0',0,20,{kind:'warmup',role:'warmup'})]);
 const group=previousActualsForRows([onlyWarmup,latest],[first,row('warm',0,'warmup')]);
 assert.equal(group.r1.set.weightKg,50,'warm-up does not replace latest working set');
 assert.equal(group.warm.set.weightKg,20,'warm-up uses its own history');
 const extra=workout('extra','26',[set('extra0',null,60,{isExtraSet:true})]);
 assert.equal(previousActualsForRows([extra],[row('bonus',null,'work',true)]).bonus.set.weightKg,60);
 const ambiguous=workout('ambig','26',[set('a',0,72,{planPositionId:'a'}),set('b',0,73,{planPositionId:'b'})]);
 assert.equal(previousActualsForRows([ambiguous],[first]).r1,undefined,'two historic positions are not guessed');
 assert.equal(previousActualsForRows([ambiguous],[{...first,planPositionId:'b'}]).r1.set.weightKg,73);
 assert.equal(previousActualsForRows([latest],[first],null,'2026-11-21T10:00:00Z').r1,undefined,'future workouts excluded');
 assert.deepEqual(previousActualsForRows([], [first]),{});
 assert.equal(older.sets[0].weightKg,40,'original data never modified');
 console.log('PASS: previous actuals, changed plans, partial sets, RIR, warm-ups, extras, ambiguity and dates.');
}finally{fs.rmSync(tmp,{recursive:true,force:true})}
